import numpy as np
import polars as pl


def generate_data(num_days, num_users, num_items, num_events):
    max_seconds = num_days * 86400 - 1
    timestamps = np.random.randint(0, max_seconds, num_events)

    raw_data = {
        "uid": np.random.randint(1, num_users + 1, num_events),
        "item_id": np.random.randint(101, 101 + num_items, num_events),
        "timestamp": timestamps,
        "event_type": np.random.choice(["like", "dislike", "listen"], num_events),
        "is_organic": np.random.choice([True, False], num_events),
    }
    df = pl.DataFrame(raw_data).sort("timestamp")

    item_ids = np.arange(101, 101 + num_items)

    artist_map = pl.DataFrame(
        {
            "item_id": item_ids,
            "artist_id": [f"Artist_{i % 5}" for i in range(num_items)],
        }
    ).filter(pl.col("item_id") % 4 != 0)

    album_map = pl.DataFrame(
        {"item_id": item_ids, "album_id": [f"Album_{i % 8}" for i in range(num_items)]}
    ).filter(pl.col("item_id") % 5 != 0)

    df = df.join(artist_map, on="item_id", how="left").join(
        album_map, on="item_id", how="left"
    )

    return df


